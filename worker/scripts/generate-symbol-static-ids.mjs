import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
for(const name of ['nature','plant','expanded','starter']) vm.runInNewContext(fs.readFileSync(new URL(`../../symbols/${name}-catalog.js`,import.meta.url),'utf8'),context);
const ids=[...Object.values(context.window).flat().map(item=>item.id),'demo-seedling','demo-incubator','demo-station'];
if(new Set(ids).size!==ids.length) throw new Error('Duplicate static asset ID');
fs.writeFileSync(new URL('../src/symbol-static-ids.js',import.meta.url),'// Generated by scripts/generate-symbol-static-ids.mjs from the public catalogs.\nexport const STATIC_SYMBOL_IDS = '+JSON.stringify(ids.sort(),null,2)+';\n');
console.log(`Registered ${ids.length} static asset IDs`);
